    @Test
    public void testDELETESession() throws IOException {
        BufferedReader csvReader = new BufferedReader(new FileReader(file));
        String row;
        csvReader.readLine(); // Skipping the Headers

        while ((row = csvReader.readLine()) != null) {
            String[] data = row.split("\\^\\|\\^");
            
            if (data.length > 0) {
                String method = data[0].trim();
                String url = data[1].trim();
                JsonObject headers = JsonParser.parseString(data[2]).getAsJsonObject();
                JsonObject body = JsonParser.parseString(data[3]).getAsJsonObject();
                int responseCode = Integer.parseInt(data[4].trim());
                JsonObject responseBody = JsonParser.parseString(data[5]).getAsJsonObject();

                if (method.equals("delete")) {
                    // Sending DELETE request
                    Response response = 
                        given().
                            headers("api_key", headers.get("api_key").getAsString()).
                            body(body.toString()).
                        when().
                            delete(url).
                        then().
                            assertThat().
                            statusCode(responseCode).
                            and().
                            body("description", equalTo(responseBody.get("description").getAsString())).
                            extract().response();
                        
                    // Assertions for 'headers' attribute in the response
                    if (responseBody.has("headers")) {
                        given().
                            headers("api_key", headers.get("api_key").getAsString()).
                            body(body.toString()).
                        when().
                            delete(url).
                        then().
                            assertThat().
                            header("headers", equalTo(responseBody.get("headers").getAsString()));

                        response.headers().forEach(header -> {
                            if (header.getName().equals("headers")) {
                                assert(header.getValue().equals(responseBody.get("headers").getAsString()));
                            }
                        });
                    }
                }
            }
        }

        csvReader.close();
    }
